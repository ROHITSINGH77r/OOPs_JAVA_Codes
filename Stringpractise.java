public class Stringpractise{
    public static void main(String[]args){
        //charAt Fxn
        String name="AbCd";
        System.out.println(name.charAt(0));
        //Length Fxn
        String n1="abcdefg";
        System.out.println(n1.length());
        //Replace Fxn
        String n2="abacada";
        String n3=n2.replace('a','z');
        System.out.println(n3);
        //Substring Fxn
        String n4="abcdefghij";
        System.out.println(n4.substring(0,3));
    }
}
